const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('kh', {
  saveFile: (name, data) => ipcRenderer.invoke('save-file', name, data),
  showInFolder: p => ipcRenderer.invoke('show-in-folder', p),
  openPath: p => ipcRenderer.invoke('open-path', p),
  dataLoadSync: () => ipcRenderer.sendSync('data-load-sync'),
  promptSync: (m, d) => ipcRenderer.sendSync('prompt-sync', String(m ?? ''), String(d ?? '')),
  dataSave: txt => ipcRenderer.invoke('data-save', txt),
  dataSaveSync: txt => ipcRenderer.sendSync('data-save-sync', txt),
  openDataDir: () => ipcRenderer.invoke('data-dir'),
  listDir: p => ipcRenderer.invoke('list-dir', p),
  readFile: p => ipcRenderer.invoke('read-file', p),
  thumb: (p, w) => ipcRenderer.invoke('thumb', p, w),
  pickDir: () => ipcRenderer.invoke('pick-dir'),
  linkInfo: () => ipcRenderer.invoke('link-info'),
  backupSet: clear => ipcRenderer.invoke('backup-set', clear),
  backupNow: () => ipcRenderer.invoke('backup-now'),
  openDir: p => ipcRenderer.invoke('open-dir', p),
  syncSet: clear => ipcRenderer.invoke('sync-set', clear),
  syncRead: () => ipcRenderer.invoke('sync-read'),
  syncBase: txt => ipcRenderer.invoke('sync-base', txt),
  syncWrite: (txt, mt) => ipcRenderer.invoke('sync-write', txt, mt),
  onSyncRemote: cb => ipcRenderer.on('sync-remote', (e, d) => cb(d)),
  mobileSet: (on, port) => ipcRenderer.invoke('mobile-set', on, port),
  mobileNewToken: () => ipcRenderer.invoke('mobile-newtoken'),
  onMobileReq: cb => ipcRenderer.on('mobile-req', (e, r) => cb(r)),
  onMobileErr: cb => ipcRenderer.on('mobile-err', (e, m) => cb(m)),
  mobileRes: (id, data) => ipcRenderer.send('mobile-res', id, data),
  printHtml: (html, opt) => ipcRenderer.invoke('print-html', html, opt),
  info: () => ipcRenderer.invoke('info'),
  setFeed: (owner, repo) => ipcRenderer.invoke('set-feed', owner, repo),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  onUpdate: cb => ipcRenderer.on('upd', (e, s) => cb(s)),
  onOpenFiles: cb => ipcRenderer.on('open-files', (e, files) => cb(files))
});
